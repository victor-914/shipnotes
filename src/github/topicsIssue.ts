import { z } from "zod";
import { describeFact, factSchema } from "../facts.js";
import type { Topic } from "../topics.js";

// The weekly topics Issue. Its body is rebuilt from a state block hidden in an
// HTML comment, so ticking a box or commenting a command needs no database.

export const TOPICS_LABEL = "shipnotes";

const stateSchema = z.strictObject({
  v: z.literal(1),
  period: z.strictObject({ from: z.string(), to: z.string() }),
  topics: z.array(
    z.strictObject({ id: z.number().int(), title: z.string(), angle: z.string(), facts: z.array(factSchema).min(1) })
  ),
  /** topic id → draft PR number */
  drafted: z.record(z.string(), z.number().int()).default({}),
});
export type TopicsState = z.output<typeof stateSchema>;

const STATE_RE = /<!-- shipnotes:state ([A-Za-z0-9+/=]+) -->/;

export function newState(period: { from: string; to: string }, topics: Topic[]): TopicsState {
  return { v: 1, period, topics, drafted: {} };
}

export function issueTitle(state: TopicsState): string {
  return `Post ideas: ${state.period.from} → ${state.period.to}`;
}

export function renderIssueBody(state: TopicsState): string {
  const lines = [
    `Topics from your projects' outcomes for **${state.period.from} → ${state.period.to}**.`,
    "",
    "Tick a topic, or comment `/shipnotes draft <number>`, and a draft pull request will be opened. Comment `/shipnotes skip` to close this without drafting.",
    "",
  ];
  for (const t of state.topics) {
    const pr = state.drafted[String(t.id)];
    lines.push(`- [${pr ? "x" : " "}] **${t.id}. ${t.title}**${pr ? ` → #${pr}` : ""}`);
    lines.push(`  ${t.angle}`);
    for (const f of t.facts) lines.push(`  <sub>${describeFact(f)}</sub>`);
    lines.push("");
  }
  lines.push("<sub>Generated by shipnotes. Numbers come only from your outcome snapshots.</sub>");
  lines.push(`<!-- shipnotes:state ${Buffer.from(JSON.stringify(state), "utf8").toString("base64")} -->`);
  return lines.join("\n");
}

export function readState(body: string | null): TopicsState | null {
  const match = (body ?? "").match(STATE_RE);
  if (!match) return null;
  try {
    const parsed = stateSchema.safeParse(JSON.parse(Buffer.from(match[1]!, "base64").toString("utf8")));
    return parsed.success ? parsed.data : null;
  } catch {
    return null;
  }
}

/** Topic ids ticked in the body that have no draft yet. */
export function newlyTicked(body: string | null, state: TopicsState): number[] {
  const ticked = [...(body ?? "").matchAll(/^- \[[xX]\] \*\*(\d+)\./gm)].map((m) => Number(m[1]));
  return ticked.filter((id) => !state.drafted[String(id)] && state.topics.some((t) => t.id === id));
}
